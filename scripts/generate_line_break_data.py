"""Generates src/FactsPDF/Text/LineBreakData.cs from the Unicode Character Database.

Usage: python scripts/generate_line_break_data.py <ucd-dir>
The directory holds LineBreak.txt, EastAsianWidth.txt and emoji-data.txt of one Unicode
version (https://www.unicode.org/Public/<version>/ucd/). Only run this to move to a new
Unicode version; the generated file is committed.
"""
import re
import sys
from pathlib import Path

CLASSES = ["XX", "AI", "AK", "AL", "AP", "AS", "B2", "BA", "BB", "BK", "CB", "CJ", "CL", "CM", "CP", "CR", "EB", "EM",
           "EX", "GL", "H2", "H3", "HL", "HY", "ID", "IN", "IS", "JL", "JT", "JV", "LF", "NL", "NS", "NU", "OP", "PO",
           "PR", "QU", "RI", "SA", "SG", "SP", "SY", "VF", "VI", "WJ", "ZW", "ZWJ"]
MAX = 0x110000


def ranges(path):
    for line in Path(path).read_text(encoding="utf-8").splitlines():
        line = line.split("#")[0].strip()
        if not line:
            continue
        span, value = [part.strip() for part in line.split(";")[:2]]
        start, _, end = span.partition("..")
        yield int(start, 16), int(end or start, 16), value.split()[0]


def main(directory):
    directory = Path(directory)
    version = re.search(r"LineBreak-(\S+)\.txt", (directory / "LineBreak.txt").read_text(encoding="utf-8")).group(1)
    classes = ["XX"] * MAX
    for start, end, value in ranges(directory / "LineBreak.txt"):
        for cp in range(start, end + 1):
            classes[cp] = value
    runs = []
    for cp, value in enumerate(classes):
        if not runs or runs[-1][1] != value:
            runs.append((cp, value))
    wide = []
    for start, end, value in ranges(directory / "EastAsianWidth.txt"):
        if value in ("F", "W", "H"):
            if wide and wide[-1][1] + 1 == start:
                wide[-1] = (wide[-1][0], end)
            else:
                wide.append((start, end))
    pictographic = [(start, end) for start, end, value in ranges(directory / "emoji-data.txt") if value == "Extended_Pictographic"]
    out = ["// <auto-generated>", f"// Generated by scripts/generate_line_break_data.py from Unicode {version} (LineBreak.txt, EastAsianWidth.txt, emoji-data.txt). Do not edit.", "// </auto-generated>",
           "namespace FactsPDF;", "", "internal static class LineBreakData", "{",
           f"    internal const string UnicodeVersion = \"{version}\";", "",
           "    // Each entry is (first scalar << 6) | class, sorted by scalar; a run lasts until the next entry.",
           "    internal static ReadOnlySpan<uint> Runs =>", "    ["]
    row = []
    for cp, value in runs:
        row.append(f"0x{(cp << 6) | CLASSES.index(value):X}")
        if len(row) == 12:
            out.append("        " + ", ".join(row) + ","); row = []
    if row:
        out.append("        " + ", ".join(row) + ",")
    out += ["    ];", "", "    // Scalars whose East Asian Width is F, W or H ($EastAsian in LB19a, LB21a and LB30), as (first, last) pairs.",
            "    internal static ReadOnlySpan<int> EastAsian =>", "    ["]
    row = []
    for start, end in wide:
        row.append(f"0x{start:X}, 0x{end:X}")
        if len(row) == 8:
            out.append("        " + ", ".join(row) + ","); row = []
    if row:
        out.append("        " + ", ".join(row) + ",")
    out += ["    ];", "", "    // Extended_Pictographic ranges as (first, last) pairs (LB30b).", "    internal static ReadOnlySpan<int> Pictographic =>", "    ["]
    row = []
    for start, end in pictographic:
        row.append(f"0x{start:X}, 0x{end:X}")
        if len(row) == 8:
            out.append("        " + ", ".join(row) + ","); row = []
    if row:
        out.append("        " + ", ".join(row) + ",")
    out += ["    ];", "}", ""]
    target = Path(__file__).resolve().parent.parent / "src" / "FactsPDF" / "Text" / "LineBreakData.cs"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"{len(runs)} runs, {len(wide)} east asian ranges, {len(pictographic)} pictographic ranges -> {target}")
    print("class order:", ",".join(CLASSES))


if __name__ == "__main__":
    main(sys.argv[1])
